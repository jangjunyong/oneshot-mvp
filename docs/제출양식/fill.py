def set_cell(cell, text):
    """셀 텍스트 교체. 첫 run 서식을 유지한 채 갈아 끼운다."""
    tf = cell.text_frame
    lines = text.split("\n")
    # 첫 문단의 첫 run 을 서식 원본으로 삼는다
    p0 = tf.paragraphs[0]
    if p0.runs:
        proto = p0.runs[0]
    else:
        proto = None
    # 문단을 하나만 남기고 정리
    for p in list(tf.paragraphs[1:]):
        p._p.getparent().remove(p._p)
    for r in list(p0.runs[1:]):
        r._r.getparent().remove(r._r)

    if proto is None:
        tf.text = text
        for para in tf.paragraphs:
            for run in para.runs:
                run.font.color.rgb = BLACK
        return
    proto.text = lines[0]
    proto.font.color.rgb = BLACK
    for line in lines[1:]:
        newp = copy.deepcopy(p0._p)
        p0._p.getparent().append(newp)
        from pptx.text.text import _Paragraph
        para = _Paragraph(newp, tf)
        for r in list(para.runs[1:]):
            r._r.getparent().remove(r._r)
        para.runs[0].text = line
        para.runs[0].font.color.rgb = BLACK


def table(slide, rows=None, cols=None, idx=0):
    ts = [sh.table for sh in slide.shapes if sh.has_table]
    if rows is not None:
        ts = [t for t in ts if len(t.rows) == rows and len(t.columns) == cols]
    return ts[idx]


def drop_guides(slide, keep_tables=True):
    """빨간 가이드 박스(직사각형 텍스트) 제거."""
    for sh in list(slide.shapes):
        if sh.has_table:
            continue
        if sh.has_text_frame and (
            "가이드" in sh.text_frame.text or "슬라이드 삭제" in sh.text_frame.text
        ):
            sh._element.getparent().remove(sh._element)


